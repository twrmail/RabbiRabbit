#!/usr/bin/env python3
"""The study catalog: which studies exist for which unit, their state, and their files. A serving Worker reads only this index and the
files it names, so it never needs a model call. usage:
  study_index.py build   # write pool/studies/index.json from every study set
  study_index.py check   # fail unless index.json equals a fresh build AND every study marked approved is servable now
A study set is a folder pool/studies/<name>/ with study-set.json ({"unit": "<unit id>", "report": "<public diagnostic file>"}),
plan-*-study-<K>.json, page-*-study-<K>.json, study-*-<K>.html and approval-records-*.json.
Status: 'approved' only when the record is approved by a named person with a timestamp; otherwise 'pending'. Only approved studies
may ever be served. Nothing here approves anything."""
import glob, hashlib, json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
REPO = os.path.normpath(os.path.join(HERE, '..', '..')); STUDIES = os.path.join(REPO, 'pool', 'studies'); INDEX = os.path.join(STUDIES, 'index.json')

def sha_file(p): return hashlib.sha256(open(p, 'rb').read()).hexdigest()
def rel(p): return os.path.relpath(p, REPO).replace(os.sep, '/')
def one(pattern):
    hits = sorted(glob.glob(pattern))
    if len(hits) != 1: raise SystemExit(f'expected exactly one file for {rel(pattern)}, found {len(hits)}')
    return hits[0]

def units():
    u = json.load(open(os.path.join(REPO, 'pool', 'units.json'))); us = u['units'] if isinstance(u, dict) and 'units' in u else u
    return {x['id']: x for x in us}

def build():
    U = units(); out = dict(schema='study_index_v1', note='Generated by tools/pool/study_index.py build. Only studies with status approved may be served.', units={})
    for d in sorted(glob.glob(os.path.join(STUDIES, '*', 'study-set.json'))):
        sd = os.path.dirname(d); meta = json.load(open(d)); uid = meta['unit']
        if uid not in U: raise SystemExit(f'{rel(d)}: unit {uid} is not in pool/units.json')
        un = U[uid]; recs = json.load(open(one(os.path.join(sd, 'approval-records-*.json'))))
        entry = out['units'].setdefault(uid, dict(title=un['title'], unit_status=un['status'], studies=[]))
        for k in sorted(recs):
            r = recs[k]; plan_p = one(os.path.join(sd, f'plan-*-study-{k}.json')); page_p = one(os.path.join(sd, f'page-*-study-{k}.json'))
            html_p = one(os.path.join(sd, f'study-*-{k}.html')); plan = json.load(open(plan_p)); page = json.load(open(page_p))
            m = re.search(r'(\d+):(\d+)(?:-(\d+))?$', plan['scope']); ch, lo = int(m.group(1)), int(m.group(2)); hi = int(m.group(3) or lo)
            if ch != un['chapter'] or lo < un['start'] or hi > un['end']: raise SystemExit(f'{rel(plan_p)}: scope {plan["scope"]} is outside unit {uid}')
            approved = r.get('status') == 'approved' and bool(r.get('approver')) and bool(r.get('timestamp'))
            entry['studies'].append(dict(
                key=k, title=page['study']['title'], shape=page['study'].get('shape'), scope=plan['scope'], verses=[lo, hi],
                status='approved' if approved else 'pending', approver=r.get('approver') if approved else None, approved_at=r.get('timestamp') if approved else None,
                frame_version=r.get('frame_version'), renderer=page.get('renderer'), fingerprints=r.get('fingerprints'),
                report=rel(os.path.join(sd, meta['report'])),
                files={n: dict(path=rel(p), sha256=sha_file(p)) for n, p in (('plan', plan_p), ('page_content', page_p), ('page_html', html_p))}))
    for e in out['units'].values():
        e['approved'] = sum(1 for s in e['studies'] if s['status'] == 'approved'); e['pending'] = len(e['studies']) - e['approved']
    return out

def text(ix): return json.dumps(ix, indent=1, ensure_ascii=False) + '\n'

def check():
    import fingerprints as F, validator as V, run_validator as RV
    fresh = text(build()); bad = []
    if not os.path.exists(INDEX) or open(INDEX).read() != fresh: bad.append('pool/studies/index.json is not equal to a fresh build (run: study_index.py build)')
    ix = json.loads(fresh)
    for uid, e in ix['units'].items():
        for s in e['studies']:
            for f in s['files'].values():
                if sha_file(os.path.join(REPO, f['path'])) != f['sha256']: bad.append(f'{uid} {s["key"]}: {f["path"]} changed')
            if s['status'] != 'approved': continue
            rep, pool, cov, req = RV.load(os.path.join(REPO, s['report'])); req['lo'], req['hi'] = s['verses']; req['scope'] = s['scope']
            page = json.load(open(os.path.join(REPO, s['files']['page_content']['path']))); plan = json.load(open(os.path.join(REPO, s['files']['plan']['path'])))
            if page['study'].get('shape'):
                req['shape'] = page['study']['shape']; req['movements'] = [[m['start'], m['end']] for m in units()[uid]['movements']]
            sd = os.path.dirname(os.path.join(REPO, s['files']['plan']['path'])); rec = json.load(open(one(os.path.join(sd, 'approval-records-*.json'))))[s['key']]
            ok, why = F.is_servable(rec, plan, pool, V.make_gaps(pool, req, cov, 'public'), req, rep, page)
            if not ok: bad.append(f'{uid} {s["key"]} is marked approved but is not servable: {why}')
    n = sum(len(e['studies']) for e in ix['units'].values()); a = sum(e['approved'] for e in ix['units'].values())
    print(f'study index: {len(ix["units"])} unit(s), {n} studies, {a} approved, {n - a} pending; ' + ('ok' if not bad else f'{len(bad)} problem(s)'))
    for b in bad: print('PROBLEM', b)
    return len(bad)

if __name__ == '__main__':
    cmd = sys.argv[1] if len(sys.argv) > 1 else 'check'
    if cmd == 'build': open(INDEX, 'w').write(text(build())); print('wrote', rel(INDEX))
    else: sys.exit(1 if check() else 0)
